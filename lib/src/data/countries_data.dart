  /// Find country by ISO 3166-1 alpha-2 code (case-insensitive).
  static CountryPhoneInfo? findByIso(String? isoCode) {
    if (isoCode == null || isoCode.isEmpty) return null;
    final clean = isoCode.trim().toUpperCase();
    for (final c in all) {
      if (c.isoCode.toUpperCase() == clean) return c;
    }
    return null;
  }

  /// Find country by dialing code (e.g. "+880" or "880").
  static CountryPhoneInfo? findByDialCode(String dialCode) {
    var clean = dialCode.trim();
    if (!clean.startsWith('+')) clean = '+$clean';
    for (final c in all) {
      if (c.dialCode == clean) return c;
    }
    return null;
  }

  /// Attempts to automatically detect the country from any input string (e.g., `+88017...` or `017...`).
  static CountryPhoneInfo? detectCountry(String input, {CountryPhoneInfo? fallback}) {
    final trimmed = input.trim();
    if (trimmed.isEmpty) return fallback ?? defaultCountry;

    // 1. Check if input starts with a '+' or dial digits
    if (trimmed.startsWith('+')) {
      // Check longest matching dial code first (e.g., +1684 before +1)
      final sortedByDialLen = List<CountryPhoneInfo>.from(all)
        ..sort((a, b) => b.dialCode.length.compareTo(a.dialCode.length));

      for (final country in sortedByDialLen) {
        if (trimmed.startsWith(country.dialCode)) {
          return country;
        }
      }
    }

    // 2. Check for Bangladesh specific condition:
    // If starts with 013, 014, 015, 016, 017, 018, 019 or 880
    final cleanDigits = trimmed.replaceAll(RegExp(r'\D'), '');
    if (cleanDigits.startsWith('880')) {
      return bangladesh;
    }
    if (bangladesh.validPrefixes.any((p) => cleanDigits.startsWith(p)) &&
        (cleanDigits.startsWith('01') || cleanDigits.startsWith('1'))) {
      return bangladesh;
    }

    return fallback ?? defaultCountry;
  }
